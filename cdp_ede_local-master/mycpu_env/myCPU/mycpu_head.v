////////////////////////////////////////////////////////////////////////////////
//  mycpu_head.v
//  五级流水线各级间总线位宽宏定义(指导书第 1 章)
//
//  约定:
//    * 字段按高位到低位拼接,顺序须与各级模块赋值语句一致。
//    * br_bus 为 ID 回传 IF 的跳转信息。
////////////////////////////////////////////////////////////////////////////////
`ifndef MYCPU_H
`define MYCPU_H

////////////////////////////////////////////////////////////////////////////////
//  BR_BUS_WD: ID -> IF 跳转总线位宽
//    [32]     br_taken  : 跳转使能
//    [31:0]   br_target : 跳转目标
////////////////////////////////////////////////////////////////////////////////
`define BR_BUS_WD           33

////////////////////////////////////////////////////////////////////////////////
//  FS_TO_DS_BUS_WD: IF -> ID 总线位宽
//    [63:32]  fs_inst : Instruction
//    [31:0]   fs_pc   : PC
////////////////////////////////////////////////////////////////////////////////
`define FS_TO_DS_BUS_WD     64

////////////////////////////////////////////////////////////////////////////////
//  DS_TO_ES_BUS_WD: ID -> EXE 总线位宽(与指导书 ID_stage 打包顺序一致)
//    [151:140] alu_op       : ALU 操作码
//    [139]     load_op      : Load 标志
//    [138]     src1_is_pc   : Src1 == PC?
//    [137]     src2_is_imm  : Src2 == Imm?
//    [136]     src2_is_4    : Src2 == 4?
//    [135]     gr_we        : GR 写使能
//    [134]     mem_we       : Mem 写使能
//    [133:129] dest         : 目的寄存器号
//    [128:97]  imm          : 立即数(已扩展)
//    [96:65]   rj_value     : rj 读出值
//    [64:33]   rkd_value    : rk/rd 读出值
//    [32:1]    ds_pc        : PC
//    [0]       res_from_mem : 结果来自 Mem?
////////////////////////////////////////////////////////////////////////////////
`define DS_TO_ES_BUS_WD     152

////////////////////////////////////////////////////////////////////////////////
//  ES_TO_MS_BUS_WD: EXE -> MEM 总线位宽
//    [104:73]  es_pc         : PC
//    [72]      mem_we        : Mem 写使能
//    [71]      gr_we         : GR 写使能
//    [70:66]   dest          : 目的寄存器号
//    [65:34]   es_alu_result : ALU 结果
//    [33:2]    rkd_value     : 存数数据
//    [1]       res_from_mem  : 结果来自 Mem?
//    [0]       load_op       : Load 标志
////////////////////////////////////////////////////////////////////////////////
`define ES_TO_MS_BUS_WD     105

////////////////////////////////////////////////////////////////////////////////
//  MS_TO_WS_BUS_WD: MEM -> WB 总线位宽
//    [69:38]  ms_pc           : PC
//    [37]     gr_we           : GR 写使能
//    [36:32]  dest            : 目的寄存器号
//    [31:0]   ms_final_result : 最终结果
////////////////////////////////////////////////////////////////////////////////
`define MS_TO_WS_BUS_WD     70

////////////////////////////////////////////////////////////////////////////////
//  WS_TO_RF_BUS_WD: WB -> 寄存器堆写端口总线位宽(与指导书 ID_stage 注释一致)
//    [37]     rf_we    : 写使能
//    [36:32]  rf_waddr : 写地址
//    [31:0]   rf_wdata : 写数据
////////////////////////////////////////////////////////////////////////////////
`define WS_TO_RF_BUS_WD     38

`endif // MYCPU_H
